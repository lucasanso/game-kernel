"""Generate cpp/core/src/ordinal_names.inc from pefile's ordlookup tables (owner: Agent A).

DLLs such as WS2_32, WSOCK32 and OLEAUT32 are often imported by ordinal only; malware relies on this to
hide names like ``connect``. The C++ PE parser resolves those ordinals with the same table pefile uses,
so detection sees the real API names. Data source: pefile (MIT license), ordlookup package.

Usage: python tools/core_gen_ordinals.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import ordlookup  # shipped with pefile

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "cpp" / "core" / "src" / "ordinal_names.inc"


def build() -> str:
    lines = [
        "// Generated by tools/core_gen_ordinals.py — do not edit.",
        "// Ordinal -> name tables for DLLs commonly imported by ordinal.",
        "// Source: pefile ordlookup (https://github.com/erocarrera/pefile), MIT license.",
        "",
    ]
    for dll in sorted(ordlookup.ords):
        ident = dll.decode().replace(".", "_")
        lines.append(f"static constexpr OrdinalName k_{ident}[] = {{")
        for ordinal, name in sorted(ordlookup.ords[dll].items()):
            lines.append(f'    {{{ordinal}, "{name.decode()}"}},')
        lines.append("};")
        lines.append("")
    lines.append("static constexpr OrdinalTable kOrdinalTables[] = {")
    for dll in sorted(ordlookup.ords):
        ident = dll.decode().replace(".", "_")
        lines.append(f'    {{"{dll.decode()}", k_{ident}, sizeof(k_{ident}) / sizeof(k_{ident}[0])}},')
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} desatualizado; rode tools/core_gen_ordinals.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
